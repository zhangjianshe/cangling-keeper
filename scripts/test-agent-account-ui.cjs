const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const html = fs.readFileSync(path.join(__dirname,'../ui/index.html'),'utf8');
const source = fs.readFileSync(path.join(__dirname,'../ui/agent.js'),'utf8');
const nodes = new Map(['agent-username','agent-avatar','agent-menu-logout'].map(id=>['#'+id,{}]));
const context=vm.createContext({$:selector=>nodes.get(selector)});
const start=source.indexOf('  function updateAccount(');
const end=source.indexOf("  window.addEventListener('keeper-login-state'",start);
vm.runInContext(source.slice(start,end),context);
context.updateAccount({loggedIn:true,username:'keeper-user',nickname:'显示名'});
assert.equal(nodes.get('#agent-username').textContent,'keeper-user');
assert.equal(nodes.get('#agent-menu-logout').disabled,false);
context.updateAccount({loggedIn:false});
assert.equal(nodes.get('#agent-username').textContent,'未登录');
assert.equal(nodes.get('#agent-menu-logout').disabled,true);
context.updateAccount({loggedIn:true,username:'苍灵用户'});
assert.equal(nodes.get('#agent-avatar').textContent,'苍灵');
assert.match(html, /<title>苍灵智能<\/title>/);
assert.match(html, /src="logo.svg"/);
assert.doesNotMatch(html,/agent-local-indicator/);
const menu=html.slice(html.indexOf('id="agent-settings-menu"'),html.indexOf('</aside>'));
assert.deepEqual([...menu.matchAll(/role="menuitem"[^>]*>([\s\S]*?)<\/button>/g)].map(m=>m[1].replace(/<[^>]+>/g,'').trim()),['账户','设置','退出','关闭服务']);
assert.match(source,/agent-menu-account'\).onclick=\(\)=>openSettings\('profile'\)/);
assert.match(source,/agent-menu-settings'\).onclick=\(\)=>openSettings\('security'\)/);
assert.match(source,/agent-menu-logout'\).onclick=async\(\)=>\{closeAccountMenu\(\);await onLogoutClick\(\)/);
console.log('Agent account UI checks passed: username/login state, menu ordering, independent settings trigger and logout routing.');
